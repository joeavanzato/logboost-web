# gunicorn.conf.py — All Gunicorn settings for LogBoost Web
# Loaded via: gunicorn --config gunicorn.conf.py "app:create_app()"

import os
import logging


# Filter to suppress noisy SSL handshake warnings from self-signed certs
# These occur when clients connect but reject the untrusted certificate
class SSLHandshakeFilter(logging.Filter):
    def filter(self, record):
        # Suppress "Invalid request" warnings caused by SSL handshake failures
        if record.levelno == logging.WARNING and "SSLV3_ALERT" in record.getMessage():
            return False
        if record.levelno == logging.WARNING and "SSL_ERROR_SSL" in record.getMessage():
            return False
        return True

# Worker configuration
# workers=1 is MANDATORY — SQLite cannot handle concurrent write locks from multiple processes
# threads=4 provides concurrency within the single process via gthread worker class
workers = 1
threads = 4
worker_class = "gthread"

# Timeout configuration
# MUST exceed the LogBoost subprocess timeout (300s in app.py run_logboost())
# If gunicorn timeout < subprocess timeout, gunicorn kills the worker mid-enrichment
timeout = 310
graceful_timeout = 30

# SSL configuration
ssl_port = os.environ.get("SSL_PORT", "8443")

# Network binding — HTTPS only
# Gunicorn cannot mix HTTP and HTTPS on different ports with global certfile/keyfile
# HEALTHCHECK uses curl -k to skip certificate verification
bind = f"0.0.0.0:{ssl_port}"

# SSL certificate paths — generated by entrypoint.sh if missing
certfile = "/data/ssl/cert.pem"
keyfile = "/data/ssl/key.pem"

# Logging — stdout/stderr for Docker log collection (per user's locked decision)
# "-" directs output to stdout (access) and stderr (error)
accesslog = "-"
errorlog = "-"
loglevel = os.environ.get("LOGBOOST_LOG_LEVEL", "info").lower()

# Apply SSL handshake filter to suppress self-signed cert warnings
logconfig_dict = {
    "version": 1,
    "disable_existing_loggers": False,
    "filters": {
        "ssl_handshake": {
            "()": SSLHandshakeFilter,
        },
    },
    "handlers": {
        "console": {
            "class": "logging.StreamHandler",
            "filters": ["ssl_handshake"],
            "stream": "ext://sys.stderr",
        },
    },
    "loggers": {
        "gunicorn.error": {
            "level": "INFO",
            "handlers": ["console"],
            "propagate": False,
        },
    },
}

# Process naming (visible in docker exec ps output)
proc_name = "logboost-web"
